# ===== 採点 =====
PUNCT = re.compile(r"[\s、。，．,.!?！？「」『』（）()・:：;；\-]")
def bigrams(s):
    s = PUNCT.sub("", s)
    return [s[i:i+2] for i in range(len(s) - 1)]
def bigram_f1(pred, ref):
    from collections import Counter
    p, r = Counter(bigrams(pred)), Counter(bigrams(ref))
    if not p or not r: return 0.0
    ov = sum((p & r).values())
    if ov == 0: return 0.0
    prec, rec = ov / sum(p.values()), ov / sum(r.values())
    return 2 * prec * rec / (prec + rec)
REFUSAL = re.compile(r"用語集に(は)?(ありません|載っていません|記載(が|は)?ありません|含まれていません|見当たりません)|確認してください")
F1_PASS = 0.5   # 用語集の定義文との文字 bigram F1 がこれ以上なら「用語集どおりに答えた」とみなす

def score(item, answer, hit_term=None):
    """hit_term: 検索の場合に、実際に引いた見出し。逆引きは「どの項目を引いたか」で判定する（定義文に正解の語が偶然出ても正解にしない）"""
    refused = bool(REFUSAL.search(answer))
    if item["cat"] == "unknown":
        return {"ok": refused, "f1": None, "refused": refused}
    if item["cat"] == "reverse":
        t = next(x for x in GLOSSARY if x["term"] == item["term"])
        ok = (hit_term == item["term"]) if hit_term is not None or answer == NOT_FOUND_TEXT else any(n.lower() in answer.lower() for n in names_of(t))
        return {"ok": ok and not refused, "f1": round(bigram_f1(answer, item["gold"]), 3), "refused": refused}
    f1 = bigram_f1(answer, item["gold"])
    return {"ok": f1 >= F1_PASS and not refused, "f1": round(f1, 3), "refused": refused}

NOT_FOUND_TEXT = "その用語はこの講座の用語集にありません。講義資料か講師に確認してください。"
CATS = ["seen", "reworded", "alias", "unknown", "reverse"]
def summarize(label, rows):
    s = {"label": label, "n": len(rows)}
    for c in CATS:
        rs = [r for r in rows if r["cat"] == c]
        s[f"{c}_acc"] = round(sum(r["ok"] for r in rs) / len(rs), 3)
        f1s = [r["f1"] for r in rs if r["f1"] is not None]
        if f1s: s[f"{c}_f1"] = round(sum(f1s) / len(f1s), 3)
    known = [r for r in rows if r["cat"] in ("seen", "reworded", "alias")]
    s["over_refusal"] = round(sum(r["refused"] for r in known) / len(known), 3)   # 用語集にある語なのに「無い」と答えた割合
    return s

