# ===== 比較対象: 用語集を「検索」して定義を返す仕組み（モデルは使わない）=====
# 1) 質問文に用語名・別名がそのまま含まれていれば、一番長く一致したものを返す（英字は単語境界で判定）
# 2) 含まれていなければ「用語集にありません」と返す
# 第 1 回のエージェントのツール（用語集検索）に近い、ごく単純なキーワード検索
INDEX = []
for t in GLOSSARY:
    for n in names_of(t):
        pat = re.compile(rf"(?<![A-Za-z]){re.escape(n)}(?![A-Za-z])", re.I) if re.fullmatch(r"[\x00-\x7f]+", n) else re.compile(re.escape(n))
        INDEX.append((n, pat, t))
NOT_FOUND = NOT_FOUND_TEXT
def retrieve(question):
    hits = [(len(n), n, t) for n, pat, t in INDEX if pat.search(question)]
    if not hits: return NOT_FOUND, None
    _, n, t = max(hits, key=lambda h: h[0])
    return f"{t['term']}: {t['definition']}", t["term"]

